ALTER TABLE stations     ADD COLUMN IF NOT EXISTS latitude  NUMERIC(9,6) CHECK (latitude  BETWEEN -90  AND 90);
ALTER TABLE stations     ADD COLUMN IF NOT EXISTS longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180);
ALTER TABLE destinations ADD COLUMN IF NOT EXISTS latitude  NUMERIC(9,6) CHECK (latitude  BETWEEN -90  AND 90);
ALTER TABLE destinations ADD COLUMN IF NOT EXISTS longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180);

CREATE TABLE IF NOT EXISTS vehicle_positions (
    position_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicles(vehicle_id)
                          ON UPDATE CASCADE ON DELETE CASCADE,
    latitude          NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude         NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    speed_kmh         NUMERIC(5,1) CHECK (speed_kmh >= 0),
    recorded_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by       INTEGER REFERENCES staff(staff_id)
                          ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_positions_vehicle_time ON vehicle_positions(vehicle_id, recorded_at DESC);

