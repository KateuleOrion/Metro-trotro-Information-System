-- Example passenger-facing query: active vehicles and latest seat information.
SELECT
    v.vehicle_id,
    v.registration_number,
    r.route_name,
    d.destination_name,
    v.vehicle_status,
    q.queue_position,
    s.available_seats,
    GREATEST(q.last_updated, s.last_updated) AS last_information_update
FROM vehicles v
JOIN routes r ON r.route_id = v.route_id
JOIN destinations d ON d.destination_id = r.destination_id
LEFT JOIN vehicle_queue q
    ON q.vehicle_id = v.vehicle_id
   AND q.queue_status IN ('waiting', 'loading')
LEFT JOIN LATERAL (
    SELECT sa.available_seats, sa.last_updated
    FROM seat_availability sa
    WHERE sa.vehicle_id = v.vehicle_id
    ORDER BY sa.last_updated DESC
    LIMIT 1
) s ON TRUE
WHERE v.vehicle_status IN ('available', 'queued', 'loading')
ORDER BY q.queue_position NULLS LAST, v.vehicle_id;
