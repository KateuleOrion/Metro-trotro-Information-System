

DROP TABLE IF EXISTS driver_requests CASCADE;
DROP TABLE IF EXISTS vehicle_positions CASCADE;
DROP TABLE IF EXISTS audit_log CASCADE;
DROP TABLE IF EXISTS offline_records CASCADE;
DROP TABLE IF EXISTS departures CASCADE;
DROP TABLE IF EXISTS seat_availability CASCADE;
DROP TABLE IF EXISTS vehicle_queue CASCADE;
DROP TABLE IF EXISTS vehicles CASCADE;
DROP TABLE IF EXISTS drivers CASCADE;
DROP TABLE IF EXISTS routes CASCADE;
DROP TABLE IF EXISTS destinations CASCADE;
DROP TABLE IF EXISTS staff CASCADE;
DROP TABLE IF EXISTS stations CASCADE;

-- 1. Stations
CREATE TABLE stations (
    station_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_name     VARCHAR(100) NOT NULL,
    location         VARCHAR(150),
    latitude         NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude        NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Destinations
CREATE TABLE destinations (
    destination_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_name VARCHAR(100) NOT NULL UNIQUE,
    description      TEXT,
    latitude         NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude        NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180)
);

-- 3. Routes
CREATE TABLE routes (
    route_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_name       VARCHAR(100) NOT NULL,
    origin           VARCHAR(100) NOT NULL,
    destination_id   INTEGER NOT NULL REFERENCES destinations(destination_id)
                         ON UPDATE CASCADE ON DELETE RESTRICT,
    station_id       INTEGER NOT NULL REFERENCES stations(station_id)
                         ON UPDATE CASCADE ON DELETE RESTRICT,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (route_name, station_id)
);

-- 4. Staff accounts
-- Staff sign in with the phone number they registered with, or their email if they registered
-- with email instead. New accounts from the registration page start as 'pending' until a station
-- manager approves them ('active') or rejects them ('rejected').
CREATE TABLE staff (
    staff_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        VARCHAR(100) NOT NULL,
    username         VARCHAR(50) UNIQUE,
    email            VARCHAR(255) UNIQUE,
    phone_number     VARCHAR(20) UNIQUE,
    password_hash    VARCHAR(255) NOT NULL,
    role             VARCHAR(30) NOT NULL
                         CHECK (role IN ('station_manager', 'station_staff')),
    account_status   VARCHAR(20) NOT NULL DEFAULT 'active'
                         CHECK (account_status IN ('pending', 'active', 'inactive', 'locked', 'rejected')),
    reject_reason    VARCHAR(255),
    reviewed_by      INTEGER REFERENCES staff(staff_id) ON UPDATE CASCADE ON DELETE SET NULL,
    reviewed_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login       TIMESTAMPTZ,
    CONSTRAINT staff_phone_or_email CHECK (phone_number IS NOT NULL OR email IS NOT NULL)
);

-- 5. Drivers
CREATE TABLE drivers (
    driver_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_name      VARCHAR(100) NOT NULL,
    phone_number     VARCHAR(20) UNIQUE
);

-- 6. Vehicles
CREATE TABLE vehicles (
    vehicle_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number VARCHAR(20) NOT NULL UNIQUE,
    route_id           INTEGER NOT NULL REFERENCES routes(route_id)
                           ON UPDATE CASCADE ON DELETE RESTRICT,
    capacity           INTEGER NOT NULL CHECK (capacity > 0),
    vehicle_status     VARCHAR(30) NOT NULL DEFAULT 'available'
                           CHECK (vehicle_status IN
                             ('available', 'queued', 'loading', 'departed', 'unavailable')),
    driver_id          INTEGER REFERENCES drivers(driver_id)
                           ON UPDATE CASCADE ON DELETE SET NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. Vehicle queue: each arrival creates a queue record.
CREATE TABLE vehicle_queue (
    queue_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicles(vehicle_id)
                          ON UPDATE CASCADE ON DELETE RESTRICT,
    station_id        INTEGER NOT NULL REFERENCES stations(station_id)
                          ON UPDATE CASCADE ON DELETE RESTRICT,
    queue_position    INTEGER NOT NULL CHECK (queue_position BETWEEN 1 AND 999),
    arrival_time      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    queue_status      VARCHAR(30) NOT NULL DEFAULT 'waiting'
                          CHECK (queue_status IN ('waiting', 'loading', 'departed', 'cancelled')),
    last_updated      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by       INTEGER REFERENCES staff(staff_id)
                          ON UPDATE CASCADE ON DELETE SET NULL,
    departed_at       TIMESTAMPTZ
);

-- A vehicle can have historical queue entries, but only one active entry.
CREATE UNIQUE INDEX uq_vehicle_active_queue
    ON vehicle_queue(vehicle_id)
    WHERE queue_status IN ('waiting', 'loading');

CREATE UNIQUE INDEX uq_station_active_queue_position
    ON vehicle_queue(station_id, queue_position)
    WHERE queue_status IN ('waiting', 'loading');

-- 8. Seat availability
CREATE TABLE seat_availability (
    seat_record_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicles(vehicle_id)
                          ON UPDATE CASCADE ON DELETE CASCADE,
    available_seats   INTEGER NOT NULL CHECK (available_seats >= 0),
    last_updated      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by       INTEGER REFERENCES staff(staff_id)
                          ON UPDATE CASCADE ON DELETE SET NULL
);

-- 9. Departures
CREATE TABLE departures (
    departure_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicles(vehicle_id)
                          ON UPDATE CASCADE ON DELETE RESTRICT,
    route_id          INTEGER NOT NULL REFERENCES routes(route_id)
                          ON UPDATE CASCADE ON DELETE RESTRICT,
    station_id        INTEGER NOT NULL REFERENCES stations(station_id)
                          ON UPDATE CASCADE ON DELETE RESTRICT,
    departure_time    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by       INTEGER REFERENCES staff(staff_id)
                          ON UPDATE CASCADE ON DELETE SET NULL
);

-- 9b. Live positions of vehicles (used by the tracking map). Each report adds one row.
CREATE TABLE vehicle_positions (
    position_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicles(vehicle_id)
                          ON UPDATE CASCADE ON DELETE CASCADE,
    latitude          NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude         NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    speed_kmh         NUMERIC(5,1) CHECK (speed_kmh >= 0),
    recorded_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by       INTEGER REFERENCES staff(staff_id)
                          ON UPDATE CASCADE ON DELETE SET NULL
);

-- 9c. Driver registration requests. A driver asks to be registered and the station manager
--     approves or rejects the request. Approving it creates the driver (and the vehicle, if given).
CREATE TABLE driver_requests (
    request_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(100) NOT NULL,
    phone_number        VARCHAR(20) NOT NULL,
    registration_number VARCHAR(20),
    destination         VARCHAR(100),
    capacity            INTEGER CHECK (capacity BETWEEN 1 AND 100),
    station_id          INTEGER NOT NULL REFERENCES stations(station_id)
                            ON UPDATE CASCADE ON DELETE RESTRICT,
    request_status      VARCHAR(20) NOT NULL DEFAULT 'pending'
                            CHECK (request_status IN ('pending', 'approved', 'rejected')),
    reject_reason       VARCHAR(255),
    submitted_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by         INTEGER REFERENCES staff(staff_id)
                            ON UPDATE CASCADE ON DELETE SET NULL,
    reviewed_at         TIMESTAMPTZ,
    driver_id           INTEGER REFERENCES drivers(driver_id)
                            ON UPDATE CASCADE ON DELETE SET NULL,
    vehicle_id          INTEGER REFERENCES vehicles(vehicle_id)
                            ON UPDATE CASCADE ON DELETE SET NULL,
    -- a vehicle needs all three details, or none of them
    CHECK ((registration_number IS NULL) = (destination IS NULL)
       AND (registration_number IS NULL) = (capacity IS NULL))
);

-- 10. Offline records waiting to be synchronised.
CREATE TABLE offline_records (
    record_id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    staff_id          INTEGER REFERENCES staff(staff_id)
                          ON UPDATE CASCADE ON DELETE SET NULL,
    record_type       VARCHAR(50) NOT NULL,
    data_payload      JSONB NOT NULL,
    creation_time     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sync_status       CHAR(1) NOT NULL DEFAULT 'P'
                          CHECK (sync_status IN ('P', 'S', 'F')),
    synced_at         TIMESTAMPTZ,
    error_message     TEXT
);

-- 11. Audit log for accountability and security monitoring.
CREATE TABLE audit_log (
    audit_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id          INTEGER REFERENCES staff(staff_id)
                          ON UPDATE CASCADE ON DELETE SET NULL,
    action            VARCHAR(100) NOT NULL,
    entity_name       VARCHAR(80) NOT NULL,
    entity_id         VARCHAR(80),
    details           JSONB,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Helpful indexes for common passenger and staff queries.
CREATE INDEX idx_routes_destination ON routes(destination_id);
CREATE INDEX idx_vehicles_route_status ON vehicles(route_id, vehicle_status);
CREATE INDEX idx_queue_station_status_position
    ON vehicle_queue(station_id, queue_status, queue_position);
CREATE INDEX idx_departures_route_time ON departures(route_id, departure_time DESC);
CREATE INDEX idx_offline_sync_status ON offline_records(sync_status, creation_time);
CREATE INDEX idx_audit_created_at ON audit_log(created_at DESC);
CREATE INDEX idx_positions_vehicle_time ON vehicle_positions(vehicle_id, recorded_at DESC);
CREATE INDEX idx_driver_requests_status ON driver_requests(request_status, submitted_at);
-- one waiting request per phone number
CREATE UNIQUE INDEX uq_driver_requests_pending_phone
    ON driver_requests(phone_number) WHERE request_status = 'pending';

